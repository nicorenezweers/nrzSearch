/// Die gewaehlte Sprache (gespeichert im Browser als `nrz_sprache`; zuerst die des Browsers).
pub fn aktuelle_sprache() -> String {
    if let Some(s) = speicher_lesen("nrz_sprache").and_then(|v| v.as_str().map(String::from)) {
        if s == "all" || TEXTE.iter().any(|(c, _)| *c == s) {
            return s;
        }
    }
    let browser = web_sys::window()
        .and_then(|w| w.navigator().language())
        .unwrap_or_else(|| "de".into())
        .chars()
        .take(2)
        .collect::<String>()
        .to_lowercase();
    if TEXTE.iter().any(|(c, _)| *c == browser) { browser } else { "de".into() }
}

/// Ein Text der Oberflaeche - in der gewaehlten Sprache, sonst deutsch, sonst der Schluessel.
pub fn t(schluessel: &str) -> String {
    let Some(i) = SCHLUESSEL.iter().position(|k| *k == schluessel) else { return schluessel.to_string() };
    let s = aktuelle_sprache();
    let texte = TEXTE.iter().find(|(c, _)| *c == s).or_else(|| TEXTE.iter().find(|(c, _)| *c == "de"));
    texte.map_or_else(|| schluessel.to_string(), |(_, t)| t[i].to_string())
}
